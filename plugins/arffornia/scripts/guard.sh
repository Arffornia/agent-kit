#!/usr/bin/env bash
# PreToolUse guard for Bash, Edit, Write, NotebookEdit and Read.
# Blocks the few actions that break Arffornia's hard rules, and says why and what to do instead.
# It sits on top of the permission deny rules in templates/.claude/settings.json, not instead of them.
# Exit 2 + stderr = blocked (Claude reads the message). Exit 0 = no opinion, normal permission flow.
set -euo pipefail
. "$(dirname "$0")/lib.sh"
read_input

have jq || have python3 || exit 0

# friction <why>: count blocks per rule and session; from the 2nd identical block on, ask the
# agent to record harness feedback (the guard may be wrong, or something keeps leading here).
friction() {
  local g f k sid n
  g="$(git -C "$(work_dir)" rev-parse --absolute-git-dir 2>/dev/null)" || return 0
  mkdir -p "$g/claude-harness" 2>/dev/null || return 0
  f="$g/claude-harness/guard-hits"
  sid="$(json_get .session_id)"; [ -n "$sid" ] || sid=nosession
  k="$sid $(printf '%s' "$1" | cut -c1-60 | hash_stdin | cut -c1-12)"
  printf '%s\n' "$k" >> "$f" 2>/dev/null || return 0
  n="$(grep -cF "$k" "$f" 2>/dev/null || echo 1)"
  if [ "${n:-1}" -ge 2 ]; then
    printf 'This guard has now blocked the same thing %s times in this session. If the rule is wrong for this case, or the task keeps leading here, record it with the arffornia:harness-feedback skill (evidence + proposed patch) before you finish.\n' "$n" >&2
  fi
}

block() { # <why> <instead>
  printf 'Blocked by the arffornia guard: %s\nDo this instead: %s\n' "$1" "$2" >&2
  friction "$1" || true
  exit 2
}

# ---------- secret-like paths -----------------------------------------------------------
is_secret_path() { # <path>
  local p="${1//\\//}" b
  b="$(basename -- "$p" 2>/dev/null || printf '%s' "$p")"
  case "$b" in
    .env.example|.env.sample|.env.template|.env.dist|.env.testing.example|*.pub|*.example|*.sample) return 1 ;;
  esac
  case "$b" in
    .env|.env.*|*.pem|*.key|*.p12|*.pfx|*.jks|*.keystore|*.kdbx|*.tfvars|*.tfstate|*.tfstate.*) return 0 ;;
    id_rsa*|id_ecdsa*|id_ed25519*|id_dsa*|.netrc|.pgpass|.npmrc|.pypirc|.vault-token|kubeconfig*) return 0 ;;
    credentials.json|credentials|service-account*.json|*-sa-key.json|client_secret*.json) return 0 ;;
  esac
  case "/$p" in
    */secrets/*|*/.ssh/*|*/.aws/*|*/.kube/config|*/.docker/config.json|*/.config/gh/*|*/.gradle/gradle.properties|*/.gnupg/*) return 0 ;;
  esac
  return 1
}

# ---------- generated / lock files (Edit, Write) ------------------------------------------
check_generated() { # <abs path>
  local p="${1//\\//}" b rel root
  p="$(phys_path "$p")"
  b="$(basename -- "$p")"
  case "$b" in
    package-lock.json|npm-shrinkwrap.json)
      block "$b is generated by npm; hand edits drift from the resolved tree and break \`npm ci\`." \
        "change package.json and run \`npm install <pkg>@<version>\` (or \`npm install\`), then commit both files." ;;
    composer.lock)
      block "composer.lock is generated by Composer; a hand edit breaks its content-hash." \
        "run \`composer require <vendor/pkg>:<constraint>\` or \`composer update <vendor/pkg>\`, then commit composer.json and composer.lock." ;;
    yarn.lock|pnpm-lock.yaml|gradle.lockfile|Cargo.lock|poetry.lock|uv.lock)
      block "$b is a generated lockfile." "change the manifest and let the package manager regenerate $b." ;;
  esac
  root="$(repo_root 2>/dev/null || true)"
  [ -n "$root" ] && root="$(cd "$root" 2>/dev/null && pwd -P || printf '%s' "$root")"
  rel="$p"; [ -n "$root" ] && rel="${p#"$root"/}"
  case "$rel" in
    src/generated/*)
      block "src/generated/ is datagen output (NeoForge GatherDataEvent providers)." \
        "change the provider under src/main/java (…/datagen/) and run \`make data\`, then commit the regenerated files." ;;
    docs/assets/diagrams/*)
      block "docs/assets/diagrams/ holds Noodle/draw.io exports." \
        "edit the model under architecture/<system>/ (model, views, layouts), run \`make lint-diagrams\` then \`make diagrams\`." ;;
    config/*/index.json)
      [ -d "$root/config/$(basename -- "$(dirname -- "$p")")/storage" ] || return 0
      block "config/<kind>/index.json is generated from storage/ (sha1 per file)." \
        "change files under config/<kind>/storage/ and run \`make indexes\` (CI also regenerates it on main)." ;;
    vendor/*|node_modules/*|public/build/*|out/*|dist/*|site/*|.gradle/*)
      block "$rel is a dependency or build output directory; edits are overwritten on the next install/build." \
        "change the source that produces it (or the dependency version), then rebuild with the Makefile target." ;;
  esac
  if is_secret_path "$p"; then
    block "$b looks like a secret file; secrets never go through an agent or into git." \
      "edit the matching .env.example (placeholders only) and tell the maintainer which value to set."
  fi
}

# ---------- Bash ------------------------------------------------------------------------
current_branch() { git -C "$(work_dir)" symbolic-ref --quiet --short HEAD 2>/dev/null || true; }
tree_dirty_tracked() { [ -n "$(git -C "$(work_dir)" status --porcelain --untracked-files=no 2>/dev/null)" ]; }
tree_has_untracked() { [ -n "$(git -C "$(work_dir)" ls-files -o --exclude-standard 2>/dev/null | head -1)" ]; }
is_protected() { case "$1" in main|master|refs/heads/main|refs/heads/master|origin/main|origin/master) return 0;; esac; return 1; }

check_push() { # words after "push"
  local w remote="" refs=() force=0 lease=0 i=0
  for w in "$@"; do
    case "$w" in
      --force|-f|--force-if-includes) force=1 ;;
      --force-with-lease|--force-with-lease=*) lease=1 ;;
      -[a-zA-Z]*f*) case "$w" in --*) ;; *) force=1 ;; esac ;;
      --all|--mirror) block "\`git push $w\` pushes every branch, including the default one." "push only your branch: \`git push -u origin HEAD\`." ;;
      --delete|-d) block "deleting remote branches is reserved to the maintainer." "leave the branch; mention it in the PR or report if it should go." ;;
      --tags|--follow-tags) block "tags and releases are reserved to the maintainer." "push the branch without tags: \`git push -u origin HEAD\`." ;;
      --repo=*|--push-option=*|-o*|--receive-pack=*|--exec=*) ;;
      -*) ;;
      *) if [ -z "$remote" ]; then remote="$w"; else refs+=("$w"); fi ;;
    esac
    i=$((i+1))
  done
  [ "$force" = 1 ] && block "force-push rewrites published history (and can destroy others' commits)." \
    "add a new commit instead. If a rebase on your own branch really needs it, ask the maintainer, or use \`git push --force-with-lease\` on your feature branch only."
  local r dst cur
  cur="$(current_branch)"
  if [ "${#refs[@]}" -eq 0 ]; then
    if is_protected "$cur"; then
      block "you are on $cur and this push would update the default branch; nobody pushes to it, the maintainer merges PRs." \
        "\`git switch -c <type>/<n>-<slug>\`, then \`git push -u origin HEAD\` and open a PR."
    fi
    return 0
  fi
  for r in "${refs[@]}"; do
    case "$r" in +*) block "a +refspec is a force-push." "push without \`+\`; add a commit instead of rewriting history." ;; esac
    case "$r" in :*) block "\`:$r\` deletes a remote branch; that is reserved to the maintainer." "leave it and mention it in the PR." ;; esac
    case "$r" in refs/tags/*|v[0-9]*) block "pushing tags is reserved to the maintainer (releases)." "push the branch only." ;; esac
    dst="${r#*:}"
    [ "$dst" = "HEAD" ] && dst="$cur"
    if is_protected "$dst"; then
      block "pushing to $dst is forbidden: the default branch only changes through a merged PR." \
        "push your branch (\`git push -u origin HEAD\` from <type>/<n>-<slug>) and open a PR."
    fi
    if [ "$lease" = 1 ] && is_protected "$dst"; then block "force-with-lease to $dst." "open a PR."; fi
  done
}

check_segment() { # one simple command
  local seg="$1" words=() w cmd i
  # shellcheck disable=SC2206
  read -r -a words <<<"$seg" || true
  [ "${#words[@]}" -gt 0 ] || return 0
  # Drop leading VAR=value, sudo, env, command, time, nohup.
  i=0
  while [ "$i" -lt "${#words[@]}" ]; do
    w="${words[$i]}"
    case "$w" in
      *=*) case "$w" in -*) break;; esac; i=$((i+1)) ;;
      sudo|env|command|time|nohup|exec|builtin|then|do|else|if|while|'{'|'!'|xargs) i=$((i+1)) ;;
      *) break ;;
    esac
  done
  words=("${words[@]:$i}")
  [ "${#words[@]}" -gt 0 ] || return 0
  cmd="$(basename -- "${words[0]}")"
  cmd="${cmd//[\'\"]/}"

  if [ "$cmd" = git ]; then
    # Skip git global options (-C dir, -c k=v, --git-dir=...).
    i=1
    while [ "$i" -lt "${#words[@]}" ]; do
      case "${words[$i]}" in
        -C|-c|--git-dir|--work-tree|--namespace) i=$((i+2)) ;;
        -*) i=$((i+1)) ;;
        *) break ;;
      esac
    done
    local sub="${words[$i]:-}" rest=("${words[@]:$((i+1))}")
    case "$sub" in
      push) check_push "${rest[@]+"${rest[@]}"}" ;;
      reset)
        case " ${rest[*]+"${rest[*]}"} " in *" --hard "*|*" --merge "*|*" --keep "*)
          if tree_dirty_tracked; then
            block "\`git reset --hard\` on a dirty tree throws away uncommitted work for good." \
              "\`git stash push -m \"<why>\"\` (or commit to a WIP branch) first, then reset; \`git stash pop\` to bring it back."
          fi ;;
        esac ;;
      clean)
        case " ${rest[*]+"${rest[*]}"} " in *" -n "*|*" --dry-run "*) ;; *" -"*f*)
          if tree_has_untracked; then
            block "\`git clean -f\` deletes untracked files that are not recoverable." \
              "run \`git clean -n\` to see the list, then delete the specific paths, or \`git stash push -u\`."
          fi ;;
        esac ;;
      checkout|restore)
        case " ${rest[*]+"${rest[*]}"} " in *" . "*)
          if tree_dirty_tracked; then
            block "\`git $sub .\` discards every uncommitted change in the tree." \
              "restore the specific files you mean, or \`git stash push -m \"<why>\"\`."
          fi ;;
        esac ;;
    esac
    return 0
  fi

  if [ "$cmd" = gh ]; then
    case " ${words[*]} " in
      *" pr merge "*|*"/merge "*|*" release create "*|*" release upload "*|*" release delete "*|*" repo delete "*|*" repo edit "*|*" secret "*)
        block "merging, releasing, repo settings and secrets are the maintainer's actions." \
          "open or update the PR and say in your report what the maintainer should merge or release." ;;
    esac
    return 0
  fi

  # Reading secret-like files through the shell.
  case "$cmd" in
    cat|less|more|head|tail|bat|batcat|nl|strings|xxd|od|hexdump|base64|grep|rg|egrep|awk|sed|jq|yq|source|.|vim|vi|nano|view|openssl|gpg|scp|curl)
      local a
      for a in "${words[@]:1}"; do
        a="${a//[\'\"]/}"
        case "$a" in -*|"") continue ;; esac
        a="${a#@}"   # curl -d @file
        if is_secret_path "$a"; then
          block "\`$cmd $a\` would read a secret-like file into the conversation." \
            "read the matching .env.example or the docs; if you need a value, ask the maintainer to provide it through the environment."
        fi
      done ;;
    cp|mv|rsync|tar|zip)
      local n=$(( ${#words[@]} - 1 )) j
      for (( j=1; j<n; j++ )); do
        a="${words[$j]//[\'\"]/}"
        case "$a" in -*) continue ;; esac
        if is_secret_path "$a"; then
          block "\`$cmd\` would copy a secret-like file ($a)." "leave secrets where they are; copy the .example file instead."
        fi
      done ;;
  esac
  return 0
}

tool="$(json_get .tool_name)"
case "$tool" in
  Bash)
    cmd="$(json_get .tool_input.command)"
    [ -n "$cmd" ] || exit 0
    # Split on ; && || | and newlines; also look inside $( ) roughly by dropping the markers.
    segs="$(printf '%s\n' "$cmd" | tr ';|&`()' '\n\n\n\n\n\n' | sed 's/^[[:space:]]*\$*//')"   # portable-ok (|& is data here)
    while IFS= read -r seg; do
      check_segment "$seg"
    done <<<"$segs"
    ;;
  Edit|Write|MultiEdit|NotebookEdit)
    f="$(json_get .tool_input.file_path)"
    [ -n "$f" ] || f="$(json_get .tool_input.notebook_path)"
    [ -n "$f" ] && check_generated "$f"
    ;;
  Read)
    f="$(json_get .tool_input.file_path)"
    if [ -n "$f" ] && is_secret_path "$f"; then
      block "$(basename -- "$f") looks like a secret file; its content must not enter the conversation." \
        "read the matching .env.example or docs; ask the maintainer for the value if a task truly needs it."
    fi
    ;;
esac
exit 0
